class Command(BaseCommand):
    help = '100% наполнение 3 класса всеми темами и упражнениями.'

    def handle(self, *args, **options):
        self.stdout.write(self.style.SUCCESS('🚀 Запуск 100% наполнения 3 класса упражнениями...'))

        subject, _ = Subject.objects.get_or_create(
            slug='russian',
            defaults={'name': 'Русский язык', 'description': 'Школьная программа РБ 1-11 класс', 'order': 1}
        )

        general_track, _ = ExamTrack.objects.get_or_create(
            subject=subject,
            track_type=ExamTrack.TrackType.GENERAL,
            defaults={'name': 'Школьная программа (1–10 классы)', 'grade_from': 1, 'grade_to': 10, 'is_active': True}
        )

        version, _ = ContentVersion.objects.get_or_create(
            subject=subject,
            year=2026,
            defaults={'title': 'Учебная программа 2026', 'is_current': True}
        )

        created_count = 0
        total_in_curriculum = len(GRADE_3_FULL_CURRICULUM)
        self.stdout.write(f'Всего подготовленных упражнений для 3 класса: {total_in_curriculum}')

        with transaction.atomic():
            for sec_name, top_name, question, opts, explanation in GRADE_3_FULL_CURRICULUM:
                section, _ = Section.objects.get_or_create(
                    exam_track=general_track,
                    name=sec_name,
                    defaults={'order': 30, 'content_version': version}
                )

                topic, _ = Topic.objects.get_or_create(
                    section=section,
                    name=top_name,
                    grade_level=3,
                    defaults={'is_active': True, 'order': 1}
                )

                TopicSummary.objects.get_or_create(
                    topic=topic,
                    defaults={
                        'title': f'Правило: {top_name}',
                        'content': explanation,
                        'key_points': explanation,
                    }
                )

                if not Task.objects.filter(topic=topic, question=question).exists():
                    task = Task.objects.create(
                        topic=topic,
                        question=question,
                        answer_format='multiple_choice',
                        difficulty=1,
                        is_active=True,
                        source='Учебник 3 класса (М.Б. Антипова, К.С. Верниковская, Мин-во образования РБ)'
                    )

                    correct_opt_text = opts[0]
                    for idx, opt_text in enumerate(opts, start=1):
                        TaskOption.objects.create(
                            task=task,
                            text=opt_text,
                            is_correct=(opt_text == correct_opt_text),
                            order=idx
                        )

                    TaskSolution.objects.create(
                        task=task,
                        correct_answer=correct_opt_text,
                        explanation=f'**Разбор:**\n{explanation}'
                    )

                    created_count += 1

        total_grade_3_now = Task.objects.filter(topic__grade_level=3).count()
        self.stdout.write(self.style.SUCCESS(
            f'✅ 3 КЛАСС ЗАВЕРШЕН НА 100%! Добавлено новых: {created_count}. Итого в 3 классе: {total_grade_3_now} заданий!'
        ))

        dump_path = 'backups/db_dump_school_enriched.json'
        self.stdout.write(f'📦 Пересохранение дампа в {dump_path}...')
        with open(dump_path, 'w', encoding='utf-8') as f:
            call_command('dumpdata', '--natural-foreign', '--natural-primary', '-e', 'contenttypes', '-e', 'auth.Permission', stdout=f)
        self.stdout.write(self.style.SUCCESS('🎉 Дамп успешно пересохранён!'))
