class Command(BaseCommand):
    help = 'Импорт структуры и стартовых заданий для классов 1–8'

    def add_arguments(self, parser):
        parser.add_argument('--clear', action='store_true', help='Удалить старые seed-задания 1–8')

    def handle(self, *args, **options):
        subject, _ = Subject.objects.get_or_create(
            slug='russian',
            defaults={'name': 'Русский язык', 'is_active': True, 'order': 1},
        )
        track, _ = ExamTrack.objects.update_or_create(
            subject=subject,
            track_type=ExamTrack.TrackType.GENERAL,
            defaults={
                'name': 'Школьная программа (1–11 классы)',
                'grade_from': 1,
                'grade_to': 11,
                'is_active': True,
            },
        )
        version, _ = ContentVersion.objects.update_or_create(
            subject=subject,
            year=2025,
            title='Школьная программа русского языка 1–8',
            defaults={'is_current': True, 'notes': 'Стартовая структура + учебные задания'},
        )

        with transaction.atomic():
            if options['clear']:
                deleted, _ = Task.objects.filter(source=SOURCE).delete()
                self.stdout.write(f'Удалено заданий seed: {deleted}')
                Section.objects.filter(
                    exam_track=track,
                    content_version=version,
                ).delete()

            topics_by_key: dict[tuple[int, str], Topic] = {}
            topics_n = 0
            for grade, sections in GRADE_PROGRAM.items():
                for s_order, (sec_name, topic_names) in enumerate(sections, start=1):
                    section, _ = Section.objects.get_or_create(
                        exam_track=track,
                        content_version=version,
                        name=f'{grade} кл. · {sec_name}',
                        defaults={'order': grade * 10 + s_order},
                    )
                    for t_order, t_name in enumerate(topic_names, start=1):
                        topic, created = Topic.objects.get_or_create(
                            section=section,
                            name=t_name,
                            defaults={
                                'grade_level': grade,
                                'order': t_order,
                                'exam_weight': 1.0,
                                'is_active': True,
                            },
                        )
                        if created:
                            topics_n += 1
                        TopicSummary.objects.update_or_create(
                            topic=topic,
                            defaults={
                                'title': f'{grade} класс: {t_name}',
                                'content': (
                                    f'Тема школьной программы {grade} класса. '
                                    f'Тренируй правило короткими заданиями по 15–20 минут в день.'
                                ),
                                'key_points': f'См. учебник русского языка {grade} класса.',
                                'source_note': f'materials/russian/{grade:02d}_klass/textbooks/',
                            },
                        )
                        topics_by_key[(grade, t_name.lower())] = topic

            tasks_n = 0
            for grade, topic_hint, question, options, explanation in STARTER_TASKS:
                topic = None
                for (g, name), t in topics_by_key.items():
                    if g == grade and topic_hint.lower() in name:
                        topic = t
                        break
                if topic is None:
                    # fallback: first topic of grade
                    topic = next((t for (g, _), t in topics_by_key.items() if g == grade), None)
                if topic is None:
                    continue
                if Task.objects.filter(topic=topic, source=SOURCE, question=question).exists():
                    continue
                task = Task.objects.create(
                    topic=topic,
                    question=question,
                    answer_format=Task.AnswerFormat.SINGLE_CHOICE,
                    scoring_scheme=Task.ScoringScheme.BINARY_1,
                    difficulty=Task.Difficulty.EASY if grade <= 4 else Task.Difficulty.MEDIUM,
                    source=SOURCE,
                    is_active=True,
                )
                for i, text in enumerate(options, start=1):
                    TaskOption.objects.create(
                        task=task,
                        text=text,
                        is_correct=(i == 1),
                        order=i,
                    )
                TaskSolution.objects.create(
                    task=task,
                    correct_answer='1',
                    explanation=explanation,
                )
                tasks_n += 1

        self.stdout.write(self.style.SUCCESS(
            f'Готово: новых тем {topics_n}, новых заданий {tasks_n}. Трек GENERAL 1–11.'
        ))
