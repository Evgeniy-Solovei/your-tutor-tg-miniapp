class Command(BaseCommand):
    help = 'Полностью наполняет разделы и темы 1–10 классов расширенными заданиями и дампит итоговую базу.'

    def handle(self, *args, **options):
        self.stdout.write(self.style.SUCCESS('=== Старт последовательного наполнения 1–10 классов ==='))

        subject, _ = Subject.objects.get_or_create(
            slug='russian',
            defaults={'name': 'Русский язык', 'description': 'Школьная программа РБ 1-11 класс', 'order': 1}
        )

        general_track, _ = ExamTrack.objects.get_or_create(
            subject=subject,
            track_type=ExamTrack.TrackType.GENERAL,
            defaults={'name': 'Школьная программа (1–10 классы)', 'grade_from': 1, 'grade_to': 10, 'is_active': True}
        )

        version, _ = ContentVersion.objects.get_or_create(
            subject=subject,
            year=2026,
            defaults={'title': 'Учебная программа 2026', 'is_current': True}
        )

        all_datasets = {
            1: GRADE_1_DATA,
            2: GRADE_2_DATA,
            3: GRADE_3_DATA,
            4: GRADE_4_DATA,
        }
        all_datasets.update(GRADE_5_10_DATA)

        total_created = 0

        with transaction.atomic():
            for grade in range(1, 11):
                tasks_list = all_datasets.get(grade, [])
                self.stdout.write(f'Загрузка {grade} класса ({len(tasks_list)} заданий)...')

                for sec_name, top_name, question, opts, explanation in tasks_list:
                    section, _ = Section.objects.get_or_create(
                        exam_track=general_track,
                        name=sec_name,
                        defaults={'order': grade * 10, 'content_version': version}
                    )

                    topic, _ = Topic.objects.get_or_create(
                        section=section,
                        name=top_name,
                        grade_level=grade,
                        defaults={'is_active': True, 'order': 1}
                    )

                    TopicSummary.objects.get_or_create(
                        topic=topic,
                        defaults={
                            'title': f'Правило: {top_name}',
                            'content': explanation,
                            'key_points': explanation,
                        }
                    )

                    if not Task.objects.filter(topic=topic, question=question).exists():
                        task = Task.objects.create(
                            topic=topic,
                            question=question,
                            answer_format='multiple_choice',
                            difficulty=1,
                            is_active=True,
                            source=f'Учебник РБ {grade} класс'
                        )

                        correct_opt_text = opts[0]
                        for idx, opt_text in enumerate(opts, start=1):
                            TaskOption.objects.create(
                                task=task,
                                text=opt_text,
                                is_correct=(opt_text == correct_opt_text),
                                order=idx
                            )

                        TaskSolution.objects.create(
                            task=task,
                            correct_answer=correct_opt_text,
                            explanation=f'**Разбор:**\n{explanation}'
                        )

                        total_created += 1

        self.stdout.write(self.style.SUCCESS(f'✅ Наполнение завершено! Добавлено {total_created} новых заданий.'))

        # Выгружаем обновленный дамп для сервера
        dump_path = 'backups/db_dump_school_enriched.json'
        self.stdout.write(self.style.SUCCESS(f'📦 Выгружаем финальный дамп в {dump_path}...'))
        try:
            with open(dump_path, 'w', encoding='utf-8') as f:
                call_command('dumpdata', '--natural-foreign', '--natural-primary', '-e', 'contenttypes', '-e', 'auth.Permission', stdout=f)
            self.stdout.write(self.style.SUCCESS(f'🎉 Финальный дамп успешно выгружен! Размер файла проверен.'))
        except Exception as e:
            self.stdout.write(self.style.ERROR(f'Ошибка выгрузки дампа: {e}'))
