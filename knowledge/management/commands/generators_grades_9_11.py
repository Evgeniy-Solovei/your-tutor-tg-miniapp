def _dispatch(topic_name: str, tb_qs):
    t = topic_name.lower()

    if 'ссп' in t or 'сложносочин' in t:
        return _ssp(tb_qs)
    if 'спп' in t or 'сложноподчин' in t or 'придаточн' in t:
        return _spp(tb_qs)
    if 'бсп' in t or 'бессоюзн' in t:
        return _bsp(tb_qs)
    if 'прямо' in t or 'диалог' in t or 'косвенн' in t or 'цитат' in t or 'эпиграф' in t or 'чуж' in t:
        return _direct_speech(tb_qs)
    if 'разных видах связи' in t or 'разные виды' in t or ('синтаксическ' in t and 'конструк' in t):
        return _complex_mixed(tb_qs)
    if 'синоними' in t:
        return _complex_mixed(tb_qs)

    if 'государственн' in t or 'международн' in t or 'развивающ' in t or 'республик' in t:
        return _belarus_lang(tb_qs)

    if 'доклад' in t or 'культур' in t or 'норм' in t or 'пароним' in t or 'коммуник' in t or 'качеств' in t:
        return _norms_culture(tb_qs)
    if 'стил' in t or 'жанр' in t or 'текст' in t or 'изложен' in t or 'отзыв' in t or 'реферат' in t:
        return _text_style(tb_qs)

    if 'фонетик' in t or 'звук' in t or 'орфоэп' in t or 'ударен' in t or 'произносительн' in t:
        return _phonetics(tb_qs)
    if 'лексик' in t or 'фразеолог' in t or 'омоним' in t or 'синоним' in t or 'антоним' in t:
        return _lexis(tb_qs)
    if 'морфем' in t or 'словообраз' in t or 'состав слова' in t:
        return _morphemics(tb_qs)
    if 'числительн' in t:
        return _numeral(tb_qs)
    if 'нареч' in t or 'местоимен' in t:
        return _pronoun_adv(tb_qs)
    if 'причасти' in t:
        return _participle(tb_qs)
    if 'деепричасти' in t:
        return _adverbial(tb_qs)
    if 'предлог' in t or 'союз' in t or 'частиц' in t or 'служебн' in t or 'междомет' in t:
        return _service_pos(tb_qs)
    if 'глагол' in t:
        return _verb(tb_qs)
    if 'существ' in t or 'прилаг' in t or 'именн' in t or 'части речи' in t or 'морфолог' in t:
        return _noun_adj(tb_qs) + _verb(tb_qs)[:20] + _service_pos(tb_qs)[:15]
    if (
        'словосочетан' in t or 'синтакс' in t or 'член' in t or 'предложен' in t
        or 'пунктуац' in t or 'запят' in t or 'тире' in t or 'двоеточ' in t
        or 'обособл' in t or 'согласован' in t
    ):
        return _syntax(tb_qs) + _complex_mixed(tb_qs)[:30]
    if 'орфограф' in t or 'написан' in t or 'ъ и ь' in t or 'проверяем' in t:
        return _ortho(tb_qs)

    if (
        'тест' in t or 'вариант' in t or 'дрт' in t or 'цт' in t or 'экзамен' in t
        or 'итогов' in t or 'повторен' in t or 'разбор' in t or 'обобщающ' in t
        or 'контрольн' in t or 'комплексн' in t or 'подготовк' in t
    ):
        return _exam_mix(tb_qs)

    return _exam_mix(tb_qs)


def generate_tasks_for_topic(topic_id, topic_name, tb_qs, count=100):
    base = _dispatch(topic_name, tb_qs)
    return _pad_to_count(base, count, topic_name)
