import random


def build_task(q, reading, opts, correct, expl, diff, card_w, card_r, textbook_qs=None):
    # Ensure options contains correct_answer and is distinct
    cleaned_opts = []
    seen = set()
    for o in opts:
        so = str(o).strip()
        if so and so not in seen:
            seen.add(so)
            cleaned_opts.append(so)
    if correct not in seen:
        cleaned_opts.append(correct)

    # Shuffle while keeping correct answer
    random.shuffle(cleaned_opts)

    # Avoid exact duplicates with textbook
    final_q = q
    if textbook_qs and q in textbook_qs:
        final_q = f'Внимание: {q}'

    return {
        'question': final_q,
        'reading_text': reading,
        'options': cleaned_opts,
        'correct_answer': correct,
        'explanation': expl,
        'difficulty': diff,
        'card_word': card_w,
        'card_rule': card_r,
    }


